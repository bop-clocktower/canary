/**
 * Source of the runnable entry that build-engine.mjs writes to
 * dist/engine/cli.js. Mirrors ts/bin/canary.js: it builds the command with the
 * published version injected and maps the CLI's business/usage exits to a
 * process exit code. `../../package.json` resolves to this package's manifest
 * (dist/engine/cli.js -> npm/package.json).
 *
 * Kept in its own module, apart from build-engine.mjs (which runs the build on
 * load), so a test can write the runner next to stub modules and execute it.
 * Every command the published bin forwards to the engine exits through this
 * code.
 */
export const RUNNER = `#!/usr/bin/env node
// GENERATED by npm/scripts/build-engine.mjs -- do not edit by hand.
// Executable counterpart of the compiled command module (cli.core.js), which
// only exports createCanaryCommand. Mirrors ts/bin/canary.js.
import { createRequire } from 'node:module';

import { CommanderError } from 'commander';

import { createCanaryCommand } from './cli.core.js';
import { CliExitError } from './cli-common.js';

const require = createRequire(import.meta.url);

function readVersion() {
  try {
    return require('../../package.json').version || 'unknown';
  } catch {
    return 'unknown';
  }
}

// Exit once stdout/stderr have drained: a bare process.exit discards queued
// writes on an async pipe (macOS, Windows), truncating piped --json (#1284).
function exitAfterDrain(code) {
  process.stdout.write('', () => {
    process.stderr.write('', () => process.exit(code));
  });
}

const program = createCanaryCommand({ pkgVersion: () => readVersion() });

try {
  await program.parseAsync(process.argv.slice(2), { from: 'user' });
} catch (err) {
  if (err instanceof CliExitError) {
    exitAfterDrain(err.code);
  } else if (err instanceof CommanderError) {
    exitAfterDrain(err.exitCode);
  } else {
    console.error(err);
    exitAfterDrain(1);
  }
}
`;
