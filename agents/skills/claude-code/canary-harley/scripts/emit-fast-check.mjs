/**
 * canary-harley -- the text of one fast-check test (vitest) for one confirmed
 * candidate.
 *
 * The seed and the run count are named constants, recorded in the header and
 * passed to `fc.assert`: an unseeded generator is a flake source.
 *
 * Text read from the analysed file reaches this output in three places only:
 * string literals (escaped by `singleQuote`), comment lines (flattened by
 * `oneLine`) and function names, which the caller has checked are
 * identifiers.
 */
import { oneLine, singleQuote, toFastCheck } from './arbitraries.mjs';

// Per kind: (function names in composition order, argument names) => line.
const BODIES = {
  'round-trip': ([first, second], [a]) =>
    `expect(${second}(${first}(${a}))).toEqual(${a});`,
  idempotence: ([f], [a]) => `expect(${f}(${f}(${a}))).toEqual(${f}(${a}));`,
  involution: ([f], [a]) => `expect(${f}(${f}(${a}))).toEqual(${a});`,
  commutativity: ([f], [a, b]) =>
    `expect(${f}(${a}, ${b})).toEqual(${f}(${b}, ${a}));`,
  'length-preserving': ([f], [a]) =>
    `expect(${f}(${a})).toHaveLength(${a}.length);`,
  'total-predicate': ([f], args) =>
    `expect(typeof ${f}(${args.join(', ')})).toBe('boolean');`,
  determinism: ([f], args) => [
    `const first = outcome(() => ${f}(${args.join(', ')}));`,
    `expect(outcome(() => ${f}(${args.join(', ')}))).toEqual(first);`,
  ],
};

// A function that throws on some input is still deterministic when it throws
// the same error twice, so determinism compares outcomes, not return values.
const OUTCOME = [
  'const outcome = (run: () => unknown) => {',
  '  try {',
  '    return { value: run() };',
  '  } catch (error) {',
  '    return { threw: String(error) };',
  '  }',
  '};',
  '',
];

const PRELUDES = { determinism: OUTCOME };

/** `a`, `b`, `c` by position. */
const argNames = (sig) =>
  sig.params.map((_param, index) => String.fromCharCode(97 + index));

function header(spec) {
  return [
    '// Generated by canary-harley. One property test for one confirmed',
    '// invariant.',
    '//',
    `// Candidate: ${oneLine(spec.candidate.id)}`,
    `// Invariant: ${oneLine(spec.candidate.statement)}`,
    `// Seed: ${spec.seed} (fixed and recorded; edit SEED to explore)`,
    `// Runs: ${spec.runs}`,
    '//',
    '// Adjust the import of the code under test if the project layout',
    '// differs. Authoring conventions, shrinking and arbitrary design:',
    '// harness-property-test.',
  ];
}

function imports(spec) {
  const names = [...spec.candidate.functions].sort().join(', ');
  return [
    "import { describe, expect, it } from 'vitest';",
    "import fc from 'fast-check';",
    '',
    `import { ${names} } from ${singleQuote(spec.importPath)};`,
  ];
}

const constants = (spec) => [
  `const SEED = ${spec.seed};`,
  `const NUM_RUNS = ${spec.runs};`,
];

function testBlock(spec) {
  const first = spec.signatures[0];
  const args = argNames(first);
  const generators = first.params.map((param) => toFastCheck(param.type));
  const body = BODIES[spec.candidate.kind](spec.candidate.functions, args);
  const title = `${spec.candidate.kind}: ${spec.candidate.statement}`;
  return [
    `describe(${singleQuote(title)}, () => {`,
    "  it('holds for generated inputs', () => {",
    '    fc.assert(',
    `      fc.property(${generators.join(', ')}, (${args.join(', ')}) => {`,
    ...[body].flat().map((line) => `        ${line}`),
    '      }),',
    '      { seed: SEED, numRuns: NUM_RUNS },',
    '    );',
    '  });',
    '});',
  ];
}

/**
 * @param {object} spec `{ candidate, signatures, importPath, stem, seed,
 *   runs }`; `signatures` are the candidate's functions in composition order
 * @returns {string} the test file's text, ending with one newline
 */
export function renderFastCheck(spec) {
  const lines = [
    ...header(spec),
    ...imports(spec),
    '',
    ...constants(spec),
    '',
    ...(PRELUDES[spec.candidate.kind] ?? []),
    ...testBlock(spec),
  ];
  return `${lines.join('\n')}\n`;
}
