/**
 * canary-harley -- the text of one Hypothesis test (pytest) for one confirmed
 * candidate.
 *
 * The seed is a named constant passed to `@seed`. `database=None` and
 * `deadline=None` switch off the two parts of Hypothesis that vary between
 * runs: the example database and the timing deadline.
 *
 * Text read from the analysed file reaches this output in comment lines
 * (flattened by `oneLine`), in the test name (reduced to word characters)
 * and as function and module names, which the caller has checked are
 * identifiers.
 */
import { oneLine, toHypothesis } from './arbitraries.mjs';

// Per kind: (function names in composition order, argument names) => line.
const BODIES = {
  'round-trip': ([first, second], [a]) =>
    `assert ${second}(${first}(${a})) == ${a}`,
  idempotence: ([f], [a]) => `assert ${f}(${f}(${a})) == ${f}(${a})`,
  involution: ([f], [a]) => `assert ${f}(${f}(${a})) == ${a}`,
  commutativity: ([f], [a, b]) => `assert ${f}(${a}, ${b}) == ${f}(${b}, ${a})`,
  'length-preserving': ([f], [a]) => `assert len(${f}(${a})) == len(${a})`,
  'total-predicate': ([f], args) =>
    `assert isinstance(${f}(${args.join(', ')}), bool)`,
  determinism: ([f], args) => [
    `first = _outcome(lambda: ${f}(${args.join(', ')}))`,
    `assert _outcome(lambda: ${f}(${args.join(', ')})) == first`,
  ],
};

// A function that raises on some input is still deterministic when it raises
// the same error twice, so determinism compares outcomes, not return values.
const OUTCOME = [
  'def _outcome(run):',
  '    try:',
  '        return ("value", run())',
  '    except Exception as error:',
  '        return ("raised", type(error).__name__, str(error))',
  '',
  '',
];

const PRELUDES = { determinism: OUTCOME };

/** `a`, `b`, `c` by position. */
const argNames = (sig) =>
  sig.params.map((_param, index) => String.fromCharCode(97 + index));

/** A test name is built from word characters only. */
const word = (text) => String(text).replace(/\W/g, '_');

function header(spec) {
  return [
    '# Generated by canary-harley. One property test for one confirmed',
    '# invariant.',
    '#',
    `# Candidate: ${oneLine(spec.candidate.id)}`,
    `# Invariant: ${oneLine(spec.candidate.statement)}`,
    `# Seed: ${spec.seed} (fixed and recorded; edit SEED to explore)`,
    `# Runs: ${spec.runs}`,
    '#',
    '# Adjust the import of the code under test if the project layout',
    '# differs. Authoring conventions, shrinking and strategy design:',
    '# harness-property-test.',
  ];
}

function imports(spec) {
  const names = [...spec.candidate.functions].sort().join(', ');
  return [
    'from hypothesis import given, seed, settings',
    'from hypothesis import strategies as st',
    '',
    `from ${spec.importPath} import ${names}`,
  ];
}

const constants = (spec) => [
  `SEED = ${spec.seed}`,
  `MAX_EXAMPLES = ${spec.runs}`,
];

function testBlock(spec) {
  const first = spec.signatures[0];
  const args = argNames(first);
  const given = first.params.map(
    (param, index) => `${args[index]}=${toHypothesis(param.type)}`,
  );
  const candidate = spec.candidate;
  const name = [spec.stem, ...candidate.functions, candidate.kind]
    .map(word)
    .join('_');
  return [
    '@seed(SEED)',
    '@settings(max_examples=MAX_EXAMPLES, database=None, deadline=None)',
    `@given(${given.join(', ')})`,
    `def test_${name}(${args.join(', ')}):`,
    ...[BODIES[candidate.kind](candidate.functions, args)]
      .flat()
      .map((line) => `    ${line}`),
  ];
}

/**
 * @param {object} spec `{ candidate, signatures, importPath, stem, seed,
 *   runs }`; `signatures` are the candidate's functions in composition order
 * @returns {string} the test file's text, ending with one newline
 */
export function renderHypothesis(spec) {
  const lines = [
    ...header(spec),
    ...imports(spec),
    '',
    ...constants(spec),
    '',
    '',
    ...(PRELUDES[spec.candidate.kind] ?? []),
    ...testBlock(spec),
  ];
  return `${lines.join('\n')}\n`;
}
